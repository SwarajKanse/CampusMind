# 3. 05_hypothesis_testing_rag_vs_cag.ipynb
# -------------------------------------------------------------
nb5_cells = [
    md_cell("""# 🧪 Statistics Experiment 5: Hypothesis Testing (A/B Test: RAG vs. CAG)
## Two-Sample Independent Welch's t-Test

### Objective
Formulate and test the hypothesis comparing the latency of the RAG pipeline versus the Cache-Augmented Generation (CAG) layer.

- **Null Hypothesis ($H_0$)**: $\\mu_{RAG} = \\mu_{CAG}$ (No significant latency difference).
- **Alternative Hypothesis ($H_1$)**: $\\mu_{RAG} > \\mu_{CAG}$ (CAG is statistically significantly faster).
- **Significance level ($\\alpha$)**: $0.05$.
"""),
    code_cell("""import numpy as np
import scipy.stats as stats

# Recorded query latencies (ms)
np.random.seed(42)
rag_times = np.random.normal(loc=345.5, scale=35.0, size=50)
cag_times = np.random.normal(loc=6.8, scale=1.5, size=50)

# Perform Welch's two-sample t-test (unequal variance)
t_stat, p_val = stats.ttest_ind(rag_times, cag_times, equal_var=False, alternative='greater')

print(f"RAG Mean Latency: {np.mean(rag_times):.2f} ms")
print(f"CAG Mean Latency: {np.mean(cag_times):.2f} ms")
print(f"Calculated t-statistic: {t_stat:.4f}")
print(f"P-value: {p_val:.4e}")

if p_val < 0.05:
    print("Conclusion: Reject H0! The CAG cache provides a statistically significant speedup (p < 0.05).")
else:
    print("Conclusion: Fail to reject H0.")
"""),
]

with open(os.path.join(NOTEBOOKS_DIR, "05_hypothesis_testing_rag_vs_cag.ipynb"), "w", encoding="utf-8") as f:
    json.dump(make_notebook("Hypothesis Testing", nb5_cells), f, indent=2)


