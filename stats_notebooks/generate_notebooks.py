nb8_cells = [
    md_cell("""# 📈 Statistics Experiment 8 & 9: Pearson Correlation & Simple Linear Regression
## Modeling Response Latency as a Function of Prompt Length

### Objective
Determine the linear correlation $r$ and fit a regression line:
$$y = \\beta_1 x + \\beta_0$$
where $x$ is the prompt character length and $y$ is the Groq LPU completion time in milliseconds.
"""),
    code_cell("""import numpy as np
import matplotlib.pyplot as plt
import scipy.stats as stats

np.random.seed(42)
prompt_lengths = np.random.uniform(20, 300, size=60)
# Latency model: base network RTT + token generation proportional to input
latency = 120 + 0.85 * prompt_lengths + np.random.normal(0, 15, size=60)

# Pearson correlation
r, p_val = stats.pearsonr(prompt_lengths, latency)
# Linear regression
slope, intercept, r_value, p_value, std_err = stats.linregress(prompt_lengths, latency)

print(f"Pearson Correlation (r): {r:.4f}")
print(f"Coefficient of Determination (R^2): {r**2:.4f}")
print(f"Regression Equation: y = {slope:.3f}x + {intercept:.3f}")

# Plot
plt.figure(figsize=(8, 5))
plt.scatter(prompt_lengths, latency, color='#06b6d4', alpha=0.8, label='Observed Queries')
plt.plot(prompt_lengths, slope * prompt_lengths + intercept, color='#7c3aed', lw=2, label='Fitted Line')
plt.title('Prompt Length vs. Response Latency Regression')
plt.xlabel('Prompt Character Length (chars)')
plt.ylabel('Latency (ms)')
plt.legend()
plt.grid(True, alpha=0.2)
plt.show()
"""),
]

