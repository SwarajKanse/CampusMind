import matplotlib.pyplot as plt
from sklearn.decomposition import PCA
from sklearn.cluster import KMeans

# 3 synthetic clusters in 384-D vector space
np.random.seed(42)
c1 = np.random.normal(loc=0.5, scale=0.1, size=(25, 384))  # Academic / Algorithms
