# 2. 04_clt_sampling_distribution.ipynb
# -------------------------------------------------------------
nb4_cells = [
    md_cell("""# 🎲 Statistics Experiment 4: Central Limit Theorem (CLT) Simulation
## CampusMind Latency Sampling Distributions

### Objective
Demonstrate that the distribution of sample means approximates a Normal Distribution $\\mathcal{N}(\\mu, \\frac{\\sigma^2}{n})$ as the sample size $n$ increases, regardless of the underlying population distribution.
"""),
    code_cell("""import numpy as np
import matplotlib.pyplot as plt
import scipy.stats as stats

# Population: heavily skewed multi-modal response time distribution
np.random.seed(42)
pop = np.concatenate([
    np.random.exponential(scale=10, size=5000),   # Fast cache hits
    np.random.normal(loc=350, scale=40, size=5000) # RAG completions
])

# Sample sizes to test
sample_sizes = [2, 10, 30, 100]
num_samples = 1000

fig, axes = plt.subplots(1, 4, figsize=(16, 3.5))

for i, n in enumerate(sample_sizes):
    sample_means = [np.mean(np.random.choice(pop, size=n, replace=True)) for _ in range(num_samples)]
    axes[i].hist(sample_means, bins=25, density=True, alpha=0.7, color='#7c3aed')
    
    # Overlay theoretical normal distribution
    mu = np.mean(pop)
    sigma = np.std(pop) / np.sqrt(n)
    x = np.linspace(min(sample_means), max(sample_means), 100)
    axes[i].plot(x, stats.norm.pdf(x, mu, sigma), 'r--', lw=2)
    axes[i].set_title(f'Sample Size n = {n}')
    axes[i].set_xlabel('Sample Mean (ms)')

plt.suptitle('Demonstration of Central Limit Theorem on CampusMind Latency', y=1.05)
plt.tight_layout()
plt.show()
"""),
]

with open(os.path.join(NOTEBOOKS_DIR, "04_clt_sampling_distribution.ipynb"), "w", encoding="utf-8") as f:
    json.dump(make_notebook("CLT", nb4_cells), f, indent=2)


